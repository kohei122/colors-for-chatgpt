from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
# Empty rows retain retired message slots; do not renumber existing keys.
rows=[line.split('|') if line.strip() else None for line in (root/'translations.tsv').read_text(encoding='utf-8-sig').splitlines()]
locales=['ja','en','ko','zh_CN','zh_TW','es','pt_BR']
assert all(len(r)==7 for r in rows if r)
assert len(set(r[0] for r in rows if r))==sum(r is not None for r in rows)
for locale in locales:
 d={f'm{i:03}':{'message':r[locales.index(locale)]} for i,r in enumerate(rows) if r}
 d['appName']={'message':'Colors for ChatGPT (by marusin)'};d['appDescription']={'message':next(r[locales.index(locale)] for r in rows if r and r[0].startswith('ChatGPTのチャット画面を好きな色と大きなタイトルで'))};d['localeCode']={'message':locale}
 p=root/'_locales'/locale/'messages.json';p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
bundle={l:json.loads((root/'_locales'/l/'messages.json').read_text(encoding='utf8')) for l in locales}
(root/'i18n-data.js').write_text('// Generated by tools/build-i18n.py from translations.tsv. Do not edit.\nglobalThis.ColorsMessages='+json.dumps(bundle,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
